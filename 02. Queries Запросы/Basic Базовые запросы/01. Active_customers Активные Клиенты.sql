-- ЗАДАЧА: Выводим список активных клиентов
-- ИСПОЛЬЗУЕМ БАЗОВЫЕ ОПЕРАТОРЫ ЗАПРОСА: SELECT, FROM, WHERE, ORDER BY
-- БИЗНЕС ПРИМЕР: Рекламная рассылка только активным клиентам
-- =====================================================

/*
   ЧТО ДЕЛАЕТ ЗАПРОС:
   - берёт из таблицы customer только активных клиентов (active = 1)
   - показывает их ID, имя, фамилию, email
   - сортирует по фамилии и имени
*/

-- ОСНОВНОЙ ЗАПРОС
SELECT 
    customer_id,
    first_name,
    last_name,
    email
FROM customer
WHERE active = 1
ORDER BY last_name, first_name;