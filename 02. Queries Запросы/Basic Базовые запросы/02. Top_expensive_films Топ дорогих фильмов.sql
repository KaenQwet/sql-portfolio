-- =====================================================
-- ЗАДАЧА: Вывести топ 10 самых дорогих фильмов (стоимость проката)
-- ИСПОЛЬЗУЕМ БАЗОВЫЕ ОПЕРАТОРЫ ЗАПРОСА: ORDER BY DESC, LIMIT
-- БИЗНЕС ПРИМЕР: анализ цен
-- =====================================================

/*
   Важный момент: 
   - rental_rate = стоимость проката на один день
   - DESC означает "по убыванию" (от больших к меньшим)
   - LIMIT 10 = показываем только первые 10 строк
*/

SELECT 
    title,
    rental_rate
FROM film
ORDER BY rental_rate DESC
LIMIT 10;